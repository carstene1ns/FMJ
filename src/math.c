#include "math.h"

int SqrTable[3000];

void MakeSqrTable(void) {
    for (int i = 0; i < 3000; i++) {
        SqrTable[i] = i * i;
    }
}

unsigned int FindSqrt(unsigned int val) {
    unsigned int centre = 1500;
    unsigned int lower = 0;
    unsigned int upper = 2999;

    while (val != SqrTable[centre]) {
        if (val <= SqrTable[centre] && val < SqrTable[centre]) {
            upper = centre;
            if (!((unsigned int)(centre - lower) >> 1))
                return centre;
            centre -= (unsigned int)(centre - lower) >> 1;
        } else {
            lower = centre;
            if (!((unsigned int)(upper - centre) >> 1))
                return centre;
            centre += (unsigned int)(upper - centre) >> 1;
        }
    }
    return centre;
}

